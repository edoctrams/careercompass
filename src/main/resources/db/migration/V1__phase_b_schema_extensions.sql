-- Career Compass Phase B: Additive Schema Extensions
-- Safe for existing Supabase schema (baseline version 0).

-- 0. Pre-flight schema verification: fail fast on unexpected schema mismatches
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = 'skills' AND column_name = 'parent_skill_id'
    ) THEN
        RAISE EXCEPTION 'Schema mismatch: skills.parent_skill_id is missing';
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = 'skills' AND column_name = 'node_type'
    ) THEN
        RAISE EXCEPTION 'Schema mismatch: skills.node_type is missing';
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM information_schema.tables
        WHERE table_schema = 'public' AND table_name = 'company_career_skills'
    ) THEN
        RAISE EXCEPTION 'Schema mismatch: company_career_skills table is missing';
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM information_schema.tables
        WHERE table_schema = 'public' AND table_name = 'question_subtopics'
    ) THEN
        RAISE EXCEPTION 'Schema mismatch: question_subtopics table is missing';
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM information_schema.tables
        WHERE table_schema = 'public' AND table_name = 'question_companies'
    ) THEN
        RAISE EXCEPTION 'Schema mismatch: question_companies table is missing';
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = 'roadmaps' AND column_name = 'company_id'
    ) THEN
        RAISE EXCEPTION 'Schema mismatch: roadmaps.company_id is missing';
    END IF;
END $$;

-- 1. Extend existing questions table (non-destructive)
ALTER TABLE questions
    ADD COLUMN IF NOT EXISTS explanation TEXT;

-- 2. Learning resources table
CREATE TABLE IF NOT EXISTS learning_resources (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    skill_id BIGINT NOT NULL REFERENCES skills(id),
    title VARCHAR(200) NOT NULL,
    description TEXT,
    resource_url VARCHAR(2048) NOT NULL,
    resource_type VARCHAR(40) NOT NULL,
    difficulty VARCHAR(40),
    language VARCHAR(40),
    provider VARCHAR(120),
    created_at TIMESTAMP NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_learning_resource_skill_url UNIQUE (skill_id, resource_url)
);

-- Link roadmap_tasks optionally to learning_resources
ALTER TABLE roadmap_tasks
    ADD COLUMN IF NOT EXISTS learning_resource_id BIGINT REFERENCES learning_resources(id);

-- 3. Question practice attempts
CREATE TABLE IF NOT EXISTS question_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    question_id BIGINT NOT NULL REFERENCES questions(id),
    selected_answer TEXT,
    is_correct BOOLEAN,
    time_spent_seconds INTEGER,
    attempted_at TIMESTAMP NOT NULL DEFAULT NOW()
);

-- 4. Skill progress history
CREATE TABLE IF NOT EXISTS skill_progress_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    skill_id BIGINT NOT NULL REFERENCES skills(id),
    previous_level INTEGER CHECK (previous_level >= 0 AND previous_level <= 5),
    new_level INTEGER NOT NULL CHECK (new_level >= 0 AND new_level <= 5),
    source VARCHAR(40) NOT NULL DEFAULT 'ASSESSMENT',
    recorded_at TIMESTAMP NOT NULL DEFAULT NOW()
);

-- 5. Seed manifest table (tracks exact seeded row IDs for safe, non-destructive rollback)
CREATE TABLE IF NOT EXISTS seed_manifest (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    migration_version VARCHAR(40) NOT NULL,
    table_name VARCHAR(80) NOT NULL,
    record_key VARCHAR(255) NOT NULL,
    record_id BIGINT,
    seeded_at TIMESTAMP NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_seed_manifest_entry UNIQUE (migration_version, table_name, record_key)
);

-- 6. Supporting indexes
CREATE INDEX IF NOT EXISTS idx_skills_parent_node ON skills (parent_skill_id, node_type);
CREATE INDEX IF NOT EXISTS idx_ccs_company_career ON company_career_skills (company_id, career_path_id);
CREATE INDEX IF NOT EXISTS idx_qsub_skill ON question_subtopics (skill_id);
CREATE INDEX IF NOT EXISTS idx_qcomp_company ON question_companies (company_id);
CREATE INDEX IF NOT EXISTS idx_lr_skill ON learning_resources (skill_id);
CREATE INDEX IF NOT EXISTS idx_qa_user_question ON question_attempts (user_id, question_id);
CREATE INDEX IF NOT EXISTS idx_sph_user_skill ON skill_progress_history (user_id, skill_id, recorded_at DESC);
